"""Version 6: native refresh credential history and session lifetime bounds."""

VERSION = 6
NAME = "native_refresh_credentials"
SQL = (
    "ALTER TABLE sessions ADD COLUMN absolute_expires_at TEXT",
    "UPDATE sessions SET absolute_expires_at = expires_at WHERE absolute_expires_at IS NULL",
    """CREATE TABLE session_refresh_credentials (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        session_id BIGINT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
        token_hash TEXT NOT NULL CHECK (token_hash ~ '^[0-9a-f]{64}$'),
        issued_at TEXT NOT NULL,
        expires_at TEXT NOT NULL,
        consumed_at TEXT,
        retry_request_id TEXT,
        retry_response_ciphertext TEXT,
        retry_response_expires_at TEXT,
        CHECK (
            (retry_request_id IS NULL AND retry_response_ciphertext IS NULL
                AND retry_response_expires_at IS NULL)
            OR (retry_request_id IS NOT NULL AND retry_response_ciphertext IS NOT NULL
                AND retry_response_expires_at IS NOT NULL)
        ),
        CHECK (retry_request_id IS NULL OR retry_request_id ~ '^[A-Za-z0-9_-]{1,64}$')
    )""",
    "CREATE UNIQUE INDEX uq_session_refresh_credentials_token_hash ON session_refresh_credentials(token_hash)",
    "CREATE UNIQUE INDEX uq_session_refresh_credentials_active_session ON session_refresh_credentials(session_id) WHERE consumed_at IS NULL",
    "CREATE INDEX ix_session_refresh_credentials_session_id ON session_refresh_credentials(session_id)",
)
