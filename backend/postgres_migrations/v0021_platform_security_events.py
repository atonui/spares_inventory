"""Version 21: global privacy-limited authentication/security events."""

VERSION = 21
NAME = "platform_security_events"

SQL = (
    """CREATE TABLE platform_security_events (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
        event TEXT NOT NULL CHECK (event IN (
            'login_succeeded','login_failed','login_blocked','account_locked',
            'password_reset_requested','password_reset_failed','password_reset_completed',
            'password_changed','session_revoked'
        )),
        outcome TEXT NOT NULL CHECK (outcome IN ('success','failure','blocked')),
        request_id UUID NOT NULL,
        ip_address TEXT,
        user_agent TEXT,
        details JSONB NOT NULL DEFAULT '{}'::jsonb,
        created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"')
    )""",
    "CREATE INDEX idx_platform_security_created ON platform_security_events(created_at DESC, id DESC)",
    "CREATE INDEX idx_platform_security_actor_created ON platform_security_events(actor_user_id, created_at DESC, id DESC)",
    "CREATE INDEX idx_platform_security_event_created ON platform_security_events(event, created_at DESC, id DESC)",
)
