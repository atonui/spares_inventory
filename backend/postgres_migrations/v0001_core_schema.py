"""Version 1: PostgreSQL core tables before tenant ownership is attached."""

VERSION = 1
NAME = "core_schema"
SQL = (
    """CREATE TABLE users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        email TEXT NOT NULL UNIQUE,
        name TEXT NOT NULL,
        password_hash TEXT NOT NULL,
        territory TEXT,
        session_token TEXT UNIQUE,
        created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"'),
        session_expires TEXT,
        failed_login_attempts INTEGER NOT NULL DEFAULT 0,
        account_locked_until TEXT,
        last_login TEXT,
        reset_token TEXT,
        reset_token_expires TEXT,
        archived_at TEXT,
        display_timezone TEXT
    )""",
    """CREATE TABLE sessions (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        session_token TEXT NOT NULL UNIQUE,
        expires_at TEXT NOT NULL,
        created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"'),
        last_activity TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"'),
        ip_address TEXT,
        user_agent TEXT,
        is_active BOOLEAN NOT NULL DEFAULT TRUE
    )""",
    """CREATE TABLE parts (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        part_number TEXT NOT NULL,
        description TEXT,
        category TEXT,
        unit_cost NUMERIC(14, 2),
        created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"'),
        archived_at TEXT
    )""",
    """CREATE TABLE stores (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        type TEXT NOT NULL,
        location TEXT,
        assigned_user_id BIGINT REFERENCES users(id),
        created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"'),
        archived_at TEXT
    )""",
    """CREATE TABLE store_types (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        type_code TEXT NOT NULL,
        type_name TEXT NOT NULL,
        description TEXT,
        is_active BOOLEAN NOT NULL DEFAULT TRUE,
        display_order INTEGER NOT NULL DEFAULT 0,
        created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"'),
        updated_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"')
    )""",
    """CREATE TABLE work_orders (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        work_order_number TEXT NOT NULL,
        customer_name TEXT,
        description TEXT,
        status TEXT NOT NULL DEFAULT 'open',
        assigned_engineer_id BIGINT REFERENCES users(id),
        created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"')
    )""",
    """CREATE TABLE inventory (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        store_id BIGINT NOT NULL,
        part_id BIGINT NOT NULL,
        quantity INTEGER NOT NULL DEFAULT 0,
        min_threshold INTEGER NOT NULL DEFAULT 0,
        work_order_id BIGINT,
        updated_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"')
    )""",
    """CREATE TABLE movements (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        from_store_id BIGINT,
        to_store_id BIGINT,
        part_id BIGINT NOT NULL,
        quantity INTEGER NOT NULL,
        movement_type TEXT NOT NULL,
        work_order_id BIGINT,
        created_by BIGINT NOT NULL REFERENCES users(id),
        notes TEXT,
        created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"')
    )""",
    """CREATE TABLE stock_transfers (
        movement_id BIGINT PRIMARY KEY,
        status TEXT NOT NULL DEFAULT 'in_transit'
            CHECK(status IN ('in_transit', 'received', 'returned')),
        source_min_threshold INTEGER NOT NULL DEFAULT 0,
        completed_by BIGINT REFERENCES users(id),
        completed_at TEXT,
        completion_note TEXT
    )""",
    """CREATE TABLE equipment (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        equipment_name TEXT NOT NULL,
        make TEXT NOT NULL,
        model TEXT NOT NULL,
        serial_number TEXT NOT NULL,
        assigned_user_id BIGINT REFERENCES users(id),
        calibration_cert_number TEXT,
        calibration_authority TEXT,
        calibration_date TEXT,
        next_calibration_date TEXT,
        status TEXT NOT NULL DEFAULT 'active',
        notes TEXT,
        created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"'),
        updated_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"')
    )""",
    """CREATE TABLE equipment_history (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        equipment_id BIGINT NOT NULL,
        action TEXT NOT NULL,
        from_user_id BIGINT REFERENCES users(id),
        to_user_id BIGINT REFERENCES users(id),
        calibration_date TEXT,
        notes TEXT,
        created_by BIGINT NOT NULL REFERENCES users(id),
        created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"')
    )""",
    """CREATE TABLE activity_logs (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT REFERENCES users(id),
        username TEXT,
        action TEXT NOT NULL,
        resource_type TEXT,
        resource_id BIGINT,
        details TEXT,
        ip_address TEXT,
        user_agent TEXT,
        status TEXT NOT NULL DEFAULT 'success',
        error_message TEXT,
        created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"')
    )""",
    """CREATE TABLE system_logs (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        level TEXT NOT NULL,
        component TEXT,
        message TEXT NOT NULL,
        details TEXT,
        created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"')
    )""",
    """CREATE TABLE system_settings (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        setting_key TEXT NOT NULL UNIQUE,
        setting_value TEXT NOT NULL,
        description TEXT,
        updated_by BIGINT REFERENCES users(id),
        updated_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"')
    )""",
    """CREATE TABLE platform_admins (
        user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
        created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"')
    )""",
    """CREATE TABLE platform_audit_events (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        actor_user_id BIGINT REFERENCES users(id),
        organization_id UUID,
        action TEXT NOT NULL,
        result TEXT NOT NULL,
        details JSONB,
        created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"')
    )""",
    """CREATE TABLE platform_announcements (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        revision TEXT NOT NULL UNIQUE,
        payload JSONB NOT NULL,
        updated_by BIGINT REFERENCES users(id),
        updated_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"')
    )""",
    "CREATE INDEX idx_activity_action ON activity_logs(action)",
    "CREATE INDEX idx_activity_created ON activity_logs(created_at)",
    "CREATE INDEX idx_activity_user ON activity_logs(user_id)",
    "CREATE INDEX idx_sessions_token ON sessions(session_token)",
    "CREATE INDEX idx_sessions_user ON sessions(user_id, is_active)",
    "CREATE INDEX idx_equipment_assigned_user ON equipment(assigned_user_id)",
    "CREATE INDEX idx_equipment_next_calibration ON equipment(next_calibration_date)",
    "CREATE INDEX idx_equipment_status ON equipment(status)",
    "CREATE INDEX idx_equipment_history_equipment ON equipment_history(equipment_id)",
    "CREATE INDEX idx_store_types_active ON store_types(is_active, display_order)",
    "CREATE INDEX idx_transfer_status ON stock_transfers(status)",
)
