"""Version 4: invitation state and encrypted transactional mail outbox."""

VERSION = 4
NAME = "tenant_administration"

SQL = (
    """CREATE TABLE organization_invitations (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        organization_id UUID NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
        email_normalized TEXT NOT NULL CHECK (email_normalized = lower(btrim(email_normalized))),
        company_role TEXT NOT NULL CHECK (company_role IN ('owner', 'admin', 'manager', 'engineer')),
        token_hash TEXT NOT NULL UNIQUE,
        invited_by BIGINT NOT NULL REFERENCES users(id),
        created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"'),
        expires_at TEXT NOT NULL,
        accepted_at TEXT,
        accepted_by BIGINT REFERENCES users(id),
        canceled_at TEXT,
        CHECK ((accepted_at IS NULL) = (accepted_by IS NULL))
    )""",
    """CREATE UNIQUE INDEX uq_pending_invitation_org_email
        ON organization_invitations (organization_id, email_normalized)
        WHERE accepted_at IS NULL AND canceled_at IS NULL""",
    "CREATE INDEX idx_invitations_org_created ON organization_invitations (organization_id, created_at DESC)",
    "ALTER TABLE organization_invitations ENABLE ROW LEVEL SECURITY",
    """CREATE POLICY tenant_organization_scope ON organization_invitations
        USING (organization_id = NULLIF(current_setting('app.organization_id', true), '')::uuid)
        WITH CHECK (organization_id = NULLIF(current_setting('app.organization_id', true), '')::uuid)""",
    """CREATE TABLE mail_outbox (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        organization_id UUID REFERENCES organizations(id) ON DELETE CASCADE,
        message_type TEXT NOT NULL CHECK (message_type IN ('organization_invitation')),
        recipient_email TEXT NOT NULL,
        encrypted_payload TEXT NOT NULL,
        idempotency_key TEXT NOT NULL UNIQUE,
        status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'claimed', 'sent', 'failed')),
        attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count BETWEEN 0 AND 6),
        available_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"'),
        lease_expires_at TEXT,
        claim_token UUID,
        sent_at TEXT,
        last_error_code TEXT CHECK (last_error_code IS NULL OR last_error_code ~ '^[a-z0-9_:-]{1,80}$'),
        created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"'),
        updated_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"'),
        CHECK ((status = 'claimed') = (claim_token IS NOT NULL AND lease_expires_at IS NOT NULL)),
        CHECK ((status = 'sent') = (sent_at IS NOT NULL))
    )""",
    "CREATE INDEX idx_mail_outbox_pending ON mail_outbox (available_at, id) WHERE status IN ('pending', 'claimed')",
)
